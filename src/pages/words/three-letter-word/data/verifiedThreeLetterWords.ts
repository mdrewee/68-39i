export const normalizeArabicWord = (word: string): string => {
  if (!word) return '';
  return word
    .trim()
    .replace(/[\u064B-\u065F\u0670]/g, '') // strip tashkeel
    .replace(/[أإآ]/g, 'ا')
    .replace(/[ى]/g, 'ي')
    .replace(/[ة]/g, 'ه');
};

