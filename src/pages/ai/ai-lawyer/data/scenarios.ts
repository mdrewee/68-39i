/**
 * Picks a case that hasn't been played in this room yet.
 * If all 100 cases have been played, resets pool.
 */
export const getNextCase = (playedCaseIds: string[] = []): CourtCase => {
  const available = ALL_100_COURT_CASES.filter((c) => !playedCaseIds.includes(c.id));
  if (available.length === 0) {
    return ALL_100_COURT_CASES[Math.floor(Math.random() * ALL_100_COURT_CASES.length)];
  }
  return available[Math.floor(Math.random() * available.length)];
};
